#ifndef _JSONHANDLER_H_
#define _JSONHANDLER_H_

#include "bootstrap.h"

#include <list>
#include <wx/string.h>

enum class JsonErrorType
{
	// json:enum
	None = -1,
	FileExistsError = 0,
	FileReadPermissionError,
	FileReadError,
	FileWritePermissionError,
	FileWriteError,
	ParseError,
	ReadValueError,
	WriteValueError
};

/**********************************************************//**
***
**  \brief Data container for errors that can happen during Json serialization.
***
***************************************************************/
struct JsonErrorItem
{
	JsonErrorItem( const JsonErrorType &type, const wxString &message, const int start = 0, const int limit = 0 )
		: errorType( type ),
		message( message ),
		offsetStart( start ),
		offsetLimit( limit )
	{
	}

	JsonErrorType errorType;

	wxString message;

	int offsetStart = 0;

	int offsetLimit = 0;

	int line = 0;

	int column = 0;
};

/*********************************************************//**
***
**

\brief Encapsulates serialisation from and to Json streams.

Layer Approach
--------------

Json serialization has 4 layers:

First: top level access implemented by this class. Loading and saving methods can be called from the program level
(methods loadJson, parseJsonFile, saveJson).

Classes that should be serialized to JSON must implememt the Jsonable interface which provides the methods fromJsonValue and toJsonValue.

Most code on this level is generated by Json metacompiler script (json_metacompiler.py). Automatic generation of code requires
that the class is listed in the script and the attributes are tagged with the "//json:start" etc. comments.

Some classes have handwritten serialization nevertheless (e.g. MColor, MBrush, MPen).

Third: Low level template functions implementing the calls of the Json API (see file JsonConverter.h).

Fourth: The API of jsoncpp (https://github.com/open-source-parsers/jsoncpp).

Error Handling
--------------

This class has a list of error messages. Each parse/write transaction can have multiple errors (e.g. wrong attribute types).

Errors are collected during seralization. Lines and columns of errors can be calculated *en bloc* by calling the
method calculateErrorLinesAndColums. Message output can be triggered by the reportErrors method.

***
***************************************************************/
class JsonHandler
{
public:

	bool loadJson( wxString filename, Jsonable* );

	Json::Value parseJsonFile( const wxString filename );

	void saveJson( wxString filename, Jsonable* );

	void addError( const JsonErrorItem &item ) { errors.push_back( item ); }

	void addReadValueError( const Json::Value&, const wxString& );

	void calculateErrorLinesAndColums();

	bool hasErrors() const { return errors.size() > 0; }

	void reportErrors();

	void clearErrors() { errors.clear(); }

	wxString getFilename() const { return filename; }
	
	static wxString getJsonCppVersion();

	std::list<JsonErrorItem> getErrors() const { return errors; }

private:

	std::pair<int,int>  calculateLineAndColumn( const char* );

	wxString filename;

	std::list<JsonErrorItem> errors;

	std::string contents;

};
	

#endif // _JSONHANDLER_H_

