def finish_jsonable():
	if verbose: print( "Finish Jsonable impls" )
	filename_jsonimpl = "src/base/jsonstubs.cpp";
	jsonimpl = open( filename_jsonimpl, 'w' )
	jsonimpl.write( '// generated\n\n' )
	jsonimpl.write( '#include "enumserializer.h"\n' )
	jsonimpl.write( '#include "JsonConverter.h"\n' )
	jsonimpl.write( '#include "json/json.h"\n\n' )

	for header in g_headerfiles:
		if verbose: print( "include header in class impl", header )
		jsonimpl.write( '#include "' + header + '.h"\n' )
	jsonimpl.write( '\n' )

	for key in g_classdefs.keys():

		if verbose: print( "finish_jsonable starts with key " + key, g_classdefs[ key ] )

		if not g_classdefs[ key ][ "jsonable" ]:
			if verbose: print( "finish_jsonable ignores non Jsonable " + key )
			continue

		if "noimpl" in g_classdefs[ key ]:
			if verbose: print( "finish_jsonable ignores noimpl " + key )
			continue

		filename = g_classdefs[ key ][ "filename" ]

		# if "in" in g_classdefs[ key ]:
		if True:
			if verbose: print( "IN for class",key )
			jsonimpl.write( "\n// IN class " + key + " defined in " + filename + " line " + str( g_classdefs[ key ][ "lineno" ]) +  "\n" )
			jsonimpl.write( "void " + key + "::fromJsonValue( const Json::Value &v, JsonHandler &jh )\n" )
			jsonimpl.write( "{\n" )

			for aname in g_classdefs[ key][ "atts" ].keys():
				if verbose: print( "  - attribute:",aname)
				jsonimpl.write( '	if ( v[ "' + aname + '" ] )\n' )
				jsonimpl.write( '	{\n' )
				jsonimpl.write( '		extractFromJson( v[ "' + aname + '" ], ' + aname + ', jh ); \n' )
				jsonimpl.write( '	}\n' )

			jsonimpl.write( "}\n\n" )

		# TODO nur IN geht nicht, weil das Itnerface implementiert werden muss
		#if "out" in g_classdefs[ key ]:
		# if "in" in g_classdefs[ key ]:
		if True:
			if verbose: print( "OUT for class",key )
			jsonimpl.write( "\n// OUT class " + key + " defined in " + filename + " line " + str( g_classdefs[ key ][ "lineno" ]) +  "\n" )
			jsonimpl.write( "Json::Value " + key + "::toJsonValue( JsonHandler &jh ) const\n" )
			jsonimpl.write( "{\n" )
			jsonimpl.write( "	Json::Value v;\n" )
			for aname in g_classdefs[ key][ "atts" ].keys():
				if verbose: print( "  - attribute:",aname)
				jsonimpl.write( '	v[ "' + aname + '" ] = writeToJson( ' + aname + ", jh );\n" )
			jsonimpl.write( "	return v;\n" )
			jsonimpl.write( "}\n\n" )

		if "ostream" in g_classdefs[ key ]:
			if verbose: print( "OSTREAM for class",key )
			if not "noimpl" in g_classdefs[ key ]:
				jsonimpl.write( "\n// STREAM output class " + key + " defined in " + filename + "\n" )
				jsonimpl.write( 'mostream& operator <<( mostream &o, const ' + key + ' &a )\n' )
				jsonimpl.write( '{\n' )
				jsonimpl.write( '	o ' )

				lineno = 0
				for aname in g_classdefs[ key ][ "atts" ].keys():
					vtype = g_classdefs[ key ][ "atts" ][ aname ][ "type" ]
					if verbose: print( "OSTREAM  - attribute:",aname,vtype)
					if lineno > 0:
						jsonimpl.write( '\n    ' )

					# cast typed enums to int
					if vtype in enumheader_map.keys():
						jsonimpl.write( '<< "' + aname + '={" << (int)a.' + aname + ' << "} "' )
					else:
						jsonimpl.write( '<< "' + aname + '={" << a.' + aname + ' << "} "' )
					lineno += 1

				jsonimpl.write( ';\n' )
				jsonimpl.write( '	return o;\n' )
				jsonimpl.write( '}\n\n' )
	jsonimpl.close()

