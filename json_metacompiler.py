def finish_enums():
	if verbose: print( "Finish Enums" )
	output_enumheader = "src/base/enumserializer.h";
	output_enumimpl = "src/base/enumserializer.cpp";
	enumheader = open( output_enumheader, 'w' )
	enumheader.write( generated_header );

	headerguard = "ENUM_SERIALIZER_H_"
	enumheader.write( '#ifndef __' + headerguard + '\n' )
	enumheader.write( '#define __' + headerguard + '\n\n' )
	enumheader.write( '#include "bootstrap.h"\n' )
	enumheader.write( '#include <wx/string.h>\n\n' )

	enumheader.write( '#ifdef CPP26\n\n' )
	enumheader.write( '#else\n\n' )

	for e in g_enumdefs.keys():
		if g_enumdefs[ e ][ "doextract" ] == True:
			if verbose: print( "Start generate enum",e)
			enumheader.write( 'enum class ' + e + ';\n' )

	enumheader.write( '\n\n' )

	for e in g_enumdefs.keys():
		if g_enumdefs[ e ][ "doextract" ] == True:
			if verbose: print( "Start generate enum methods",e)
			enumheader.write( '// ' + e + ' (' + g_enumdefs[ e ][ "origfile" ] + " line " + str(g_enumdefs[ e ][ "lineno" ]) + ')\n' )
			enumheader.write( 'wxString enum_to_string( const ' + e + '& );\n' )
			enumheader.write( 'void string_to_enum( const wxString&, ' + e + '& );\n\n' )

	# finish enum header file
	enumheader.write( '#endif // CPP26\n' )
	enumheader.write( '#endif // __' + headerguard + '\n' )
	enumheader.close()

	enumimpl = open( output_enumimpl, 'w' )
	enumimpl.write( generated_header );
	enumimpl.write( '#ifdef CPP26\n\n' )

	enumimpl.write( '#else\n\n' )
	enumimpl.write( '#include "enumserializer.h"\n' )

	# includes impl
	headerlist = []
	for e in g_enumdefs.keys():
		if g_enumdefs[ e ][ "doextract" ] == True:

			includename = re.sub( "^.*/", "", g_enumdefs[ e ][ "origfile" ] )
			if verbose: print( "header deps for enum",e, "-> ", includename)
			if not includename in headerlist:
				headerlist += [ includename ]
	for filename in headerlist:
		enumimpl.write( '#include "' + filename + '"\n' )
	enumimpl.write( '#include <map>\n' )
	enumimpl.write( '\n' )

	for e in g_enumdefs.keys():
		if g_enumdefs[ e ][ "doextract" ] == True:
			if verbose: print( "Start generate enum functions",e)
			mappinglist = 'mapping_list_' + e
			enumimpl.write( '/***********************************\n' )
			enumimpl.write( '*\n' )
			enumimpl.write( '* enum ' + e + '\n' )
			enumimpl.write( '*\n' )
			enumimpl.write( '************************************/\n' )
			#enumimpl.write( 'const static std::map<' + e + ', wxString> ' + mappinglist + ' =\n' )
			enumimpl.write( 'const static std::list<std::pair<' + e + ', wxString>> ' + mappinglist + ' =\n' )
			enumimpl.write( '{\n' )
			for att in g_enumdefs[ e ][ "atts" ]:
				enumimpl.write( '	{ ' + e + '::' + att + ', "' + att + '" },\n' )
			enumimpl.write( '};\n\n' )

			enumimpl.write( 'wxString enum_to_string( const ' + e + ' &a )\n' )
			enumimpl.write( '{\n' )
			enumimpl.write( '	for( const auto &p : ' + mappinglist + ' ) \n' )
			enumimpl.write( '	{\n' )
			enumimpl.write( '		if ( p.first == a )\n' )
			enumimpl.write( '		{\n' )
			enumimpl.write( '		 return p.second;\n' )
			enumimpl.write( '		}\n' )
			enumimpl.write( '	}\n' )
			# enumimpl.write( '	return "None";\n' )
			enumimpl.write( '	mstringstream m;\n' )
			enumimpl.write( '	m << "None (" << (int)a << ")";\n' )
			enumimpl.write( '	return m.str();\n' )
			enumimpl.write( '}\n\n' )

			enumimpl.write( 'void string_to_enum( const wxString &s, ' + e + ' &x )\n' )
			enumimpl.write( '{\n' )
			enumimpl.write( '	for( const auto &p : ' + mappinglist + ' ) \n' )
			enumimpl.write( '	{\n' )
			enumimpl.write( '		if ( p.second == s )\n' )
			enumimpl.write( '		{\n' )
			enumimpl.write( '		 x = p.first;\n' )
			enumimpl.write( '		 return;\n' )
			enumimpl.write( '		}\n' )
			enumimpl.write( '	}\n' )
			enumimpl.write( '	errorlog << "Cannot convert string \\"" << s << "\\" to scoped enum of type ' + e + '";\n' )
			enumimpl.write( '	x = ' + e + '::None;\n' )
			enumimpl.write( '}\n\n' )

			#enumimpl.write( 'mostream& operator <<( mostream &o, const ' + e + '&a )\n' )
			#enumimpl.write( '{\n' )
			#enumimpl.write( '	o << enum_to_string( a );\n' )
			#enumimpl.write( '	return o;\n' )
			#enumimpl.write( '}\n\n' )

	enumimpl.write( '#endif // CPP26\n' )
	enumimpl.close()

