"""
This script generates stubs for JSON serialization for the Jsoncpp implementation.

Purpose is to generate serialization code for numerous emums (enum to string and vice versa)
and Json serialization of data structs.

Generated code is written to files jsonclasses.h/.cpp and enumserializer.h/.cpp

JSON meta attributes are declared inside the class definitions as commment with prefix "json:".

Options
  // json:start
  // json:end
  // json:noimpl
  // json:ostream

Supported keywords are
- start: all following attributs should be included in Json serialization list
- end: rest of the attributes will be ignored
- noimpl: generate declaration only (i.e. custom impl elsewhere)
- ostream: generate operator<<

Restrictions
The implementation is far from mature. Known restirctions are
- order of definition should be as required (no forward decl or sort included)
- attributes with own json serializers must be imported before usage (can be other file)
- no newlines supported inside class oder attribute definitions
- no spaces allowed inside type declaration (eg. "list<int, double>" not supported)
- no multiline comments within generator section

"""

import os
import re
import sys

basenames = []
g_classnames = []
g_enumdefs = {}
g_classdefs = {}
g_enumdeps = []
g_headerfiles = []
generated_header = "// generated by " + os.path.basename(__file__) + "\n\n";

# enum to string mapping: include def header if it occurs 
enumheader_map = {}
# 
verbose = True
verbose = False
verboseError = True

########################################################
#
#  inspect header file and extract enum and json serialization information
#
########################################################
def do_header_file( filename ):

	print( "File:",filename)
	fntrunc = re.sub( r'\.h$', "", filename )
	fnbasename = re.sub( r'^.*\/', "", fntrunc )
	global g_headerfiles
	g_headerfiles += [ fnbasename ]
	if verbose: print( "Start file",filename,"filename trunc",fntrunc, "basename",fnbasename)
	level = 0;

	current_class = None
	current_enum = None
	do_extract_attributes = False
	do_write_cppfile = False
	depincludes = []

	INCLUDEDEFEX = re.compile( r'#include\s*"(.+)\.h"\s*$' )
	JSONMETADEF = re.compile( r'^\s*\/\/\s*json\s*:\s*(\w+)$' )
	INHERITDEFEX = re.compile( r'^\s*(class|struct)\s+(\w+)\s*:\s*public\s+(\w+)\s*$' )

	ATTRIBUTDEF = re.compile( r'^\s*([\w\<\>\,\:]+)\s+(\w+)\s*(=\s*[\w\.:_"}{,]+)?\s*;\s*' )

	ENUMDEFEX = re.compile( r'^\s*enum\s+class\s+(\w+)\s*$' )
	ENUMATTRIBUTE = re.compile( r'^\s*(\w+)\s*,?\s*[\/\/]??.*' )
	ENUMATTRIBUTE2 = re.compile( r'^\s*(\w+)\s*=[\s\-](\-?[\w+\d\+\s]+).*$' )

	def add_class( name, filename, lineno, parent = None ):

		c = {}
		if parent != None and parent != "Jsonable" and g_classdefs[ parent ][ "jsonable" ]:
			c[ "jsonable" ] = True
		elif parent == "Jsonable":
			c[ "jsonable" ] = True
			parent = None
		else:
			c[ "jsonable" ] = False
		
		if verbose: print( "Start add_class",name,"parent", parent, "jsonable",c[ "jsonable" ] )

		c[ "name" ] = name
		c[ "filename" ] = filename
		c[ "lineno" ] = lineno
		c[ "atts" ] = {}
		c[ "basename" ] = fnbasename
		c[ "filename" ] = filename
		global g_classnames
		g_classnames += [ name ]
		if parent != None: c[ "parent" ] = parent
		return c

	def add_enum( name, origfile, lineno ):
		c = {}
		c[ "atts" ] = []
		c[ "doextract" ] = False
		c[ "origfile" ] = origfile
		c[ "lineno" ] = lineno
		return c

	lineno = 0
	with open(filename) as infile:
		for line in infile:
			lineno += 1

			if re.match( r'^\s*$', line ):
				# print( "Empty: #",line,"#")
				continue

			# print( "LINE: #",line,"#")
			
			# find includes and add corresponding mocs to deplist
			match = re.search( INCLUDEDEFEX, line ) 
			if match:
				depinc = match.group(1)
				if verbose: print( "Found include",depinc)
				# depincludes += [ depinc ]
				if depinc not in depincludes:
					depincludes += [ depinc ]

			# start typed enum
			match = re.search( ENUMDEFEX, line ) 
			if match:
				current_enum = match.group(1)
				if verbose: print( "Start enum",current_enum )
				do_extract_attributes = True
				g_enumdefs[ current_enum ] = add_enum( current_enum, filename, lineno )
				continue

			if current_enum != None:
				match = re.search( ENUMATTRIBUTE2, line ) 
				if match and current_enum and do_extract_attributes:
					value = match.group(2)
					if verbose: print( "enum attribute (2)",match.group(1), "with value", value )

					# test if value has to be added
					if re.match( r'^First', match.group(1) ) or re.match( r'^Last', match.group(1) ):
						if verbose: print( "Skip First or Last entry ", value )
						# ignore
					elif re.match( r'^[\d\-]*$', value ):
						if verbose: print( "ADD numeric", value )
						g_enumdefs[ current_enum ][ "doextract" ] = True
						g_enumdefs[ current_enum ][ "atts" ] += [match.group(1)]
					elif re.match( r'^[\w:\s\+]*$', value ):
						if verbose: print( "ADD string value", value )
						g_enumdefs[ current_enum ][ "doextract" ] = True
						g_enumdefs[ current_enum ][ "atts" ] += [match.group(1)]
					else:
						if verbose: print( "no match", value )
						
				else:
					match = re.search( ENUMATTRIBUTE, line ) 
					if match and current_enum and do_extract_attributes:
						if verbose: print( "enum attribute (1)",match.group(1) )
						g_enumdefs[ current_enum ][ "doextract" ] = True
						g_enumdefs[ current_enum ][ "atts" ] += [match.group(1)]

			# start class/struct with inheritance
			match = re.search( INHERITDEFEX, line ) 
			if match:
				do_extract_attributes = False
				classname = match.group(2)
				parent = match.group(3)
				if verbose: print( "Found inherited class",classname, "parent",parent )

				if parent == "Jsonable" or parent in g_classdefs:
					current_class = classname
					do_extract_attributes = False
					g_classdefs[ current_class ] = add_class( current_class, filename, lineno, parent = match.group(3) )
					g_classdefs[ current_class ][ "type" ] = match.group(1)
					continue

			# json metattributes defs are: json:start, json:end, json:noimpl
			match = re.findall( JSONMETADEF, line ) 
			if match:
				verb = match[0]
				if verbose: print( "METADEF:#" + verb  + "#" )

				if verb == "start":
					do_extract_attributes = True
				elif verb == "end":
					do_extract_attributes = False
				elif verb == "noimpl":
					do_extract_attributes = False
					g_classdefs[ current_class ][ verb ] = True
				elif verb == "ostream":
					g_classdefs[ current_class ][ verb ] = True
				elif verb == "enum":
					pass
				else:
					if verboseError:  print( "ERROR: unknown metadef verb", verb )
					# sys.exit(1)

			# attribute definition
			if current_class != None and do_extract_attributes == True:
				match = re.search( ATTRIBUTDEF, line ) 
				if match:
					vtype = match.group(1)
					if vtype in [ "return" ] : break;
					vname = match.group(2)

					if verbose: print( "found attribute name: ",vname," with type",vtype)
					g_classdefs[ current_class ][ "atts" ][ vname ] = {}
					g_classdefs[ current_class ][ "atts" ][ vname ][ "type" ] = vtype
					if vtype in enumheader_map and enumheader_map[ vtype  ] not in depincludes:
						depincludes += [ enumheader_map[ vtype  ]]
						if verbose: print( "enum to header: ",vtype, " -> ", enumheader_map[ vtype  ])
				else:
					if verbose: print( "no valid attribute in line ", line )
					

			elif current_class != None:
				if verbose: print( "DO NOT extract line",line)

			if re.findall( '{', line ):
				level += 1;
				if verbose: print( "level is now",level );

			if re.findall( '}', line ):
				level -= 1;
				if verbose: print( "level is now",level );
				if level == 0 and re.findall( '};', line ):
					if current_class != None:
						if verbose: print( "end class",current_class)
						current_class=None
						do_extract_attributes = False
					elif current_enum != None:
						if verbose: print( "end enum",current_enum)
						current_enum=None
						do_extract_attributes = False

